create table if not exists public.module_entitlements (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  grant_type text not null check (grant_type in ('module', 'bundle', 'syllabus')),
  target_id text not null check (length(btrim(target_id)) > 0),
  access_level text not null default 'student' check (access_level in ('student', 'teacher')),
  source text not null check (source in ('legacy', 'pin', 'admin', 'teacher_assignment')),
  created_by uuid references auth.users(id) on delete set null,
  starts_at timestamptz not null default now(),
  expires_at timestamptz,
  revoked_at timestamptz,
  created_at timestamptz not null default now(),
  check (expires_at is null or expires_at > starts_at)
);

comment on table public.module_entitlements is
  'Auditable module, bundle, and syllabus grants. Client accounts cannot write this table directly.';

create unique index if not exists module_entitlements_one_active_grant_idx
  on public.module_entitlements (user_id, grant_type, target_id, access_level)
  where revoked_at is null;

create index if not exists module_entitlements_user_active_idx
  on public.module_entitlements (user_id, starts_at, expires_at)
  where revoked_at is null;

create index if not exists module_entitlements_target_idx
  on public.module_entitlements (grant_type, target_id)
  where revoked_at is null;

alter table public.module_entitlements enable row level security;

drop policy if exists "Users can read own module entitlements" on public.module_entitlements;
create policy "Users can read own module entitlements"
on public.module_entitlements
for select
to authenticated
using (
  (select auth.uid()) is not null
  and user_id = (select auth.uid())
);

drop policy if exists "Admins can read module entitlements" on public.module_entitlements;
create policy "Admins can read module entitlements"
on public.module_entitlements
for select
to authenticated
using (
  exists (
    select 1
    from public.user_profiles
    where user_profiles.id = (select auth.uid())
      and user_profiles.tier = 'admin'
  )
);

