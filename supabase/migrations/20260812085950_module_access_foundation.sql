grant select on public.module_entitlements to authenticated;
grant all on public.module_entitlements to service_role;
grant usage, select on sequence public.module_entitlements_id_seq to service_role;

grant select on public.modules to anon, authenticated;

-- Copy every recognised legacy unlock into the auditable grant table. The old
-- array remains untouched and is read as a fallback during the transition.
with legacy_entries as (
  select
    profiles.id as user_id,
    legacy.value
  from public.user_profiles as profiles
  cross join lateral unnest(coalesce(profiles.unlocked_modules, '{}'::text[])) as legacy(value)
), classified as (
  select
    legacy_entries.user_id,
    case
      when legacy_entries.value = 'Social_Media_Masterclass' then 'module'
      when exists (select 1 from public.modules where modules.id = legacy_entries.value) then 'module'
      when exists (select 1 from public.modules where modules.bundle = legacy_entries.value) then 'bundle'
      when exists (select 1 from public.modules where modules.syllabus = legacy_entries.value) then 'syllabus'
      else null
    end as grant_type,
    case
      when legacy_entries.value = 'Social_Media_Masterclass' then 'spm-en-social-media'
      else legacy_entries.value
    end as target_id
  from legacy_entries
)
insert into public.module_entitlements (
  user_id,
  grant_type,
  target_id,
  access_level,
  source
)
select
  classified.user_id,
  classified.grant_type,
  classified.target_id,
  'student',
  'legacy'
from classified
where classified.grant_type is not null
  and not exists (
    select 1
    from public.module_entitlements as existing
    where existing.user_id = classified.user_id
      and existing.grant_type = classified.grant_type
      and existing.target_id = classified.target_id
      and existing.access_level = 'student'
      and existing.revoked_at is null
  );

create or replace function public.can_launch_module(p_module_id text)
returns jsonb
language plpgsql
stable
security invoker
set search_path = ''
as $$
declare
  requested_module public.modules%rowtype;
  current_user_id uuid := (select auth.uid());
  current_tier text;
  current_legacy_unlocks text[] := '{}'::text[];
  matched_grant record;
  legacy_type text;
  legacy_target text;
begin
  if p_module_id is null or length(btrim(p_module_id)) = 0 then
    return jsonb_build_object(
      'allowed', false,
      'reason', 'invalid_module_id',
      'effective_role', 'guest',
      'module_id', p_module_id,
      'access_mode', null,
      'matched_grant_type', null,
      'matched_grant_target', null
    );
  end if;

  select modules.*
  into requested_module
  from public.modules
  where modules.id = p_module_id
    and coalesce(modules.is_active, true)
  limit 1;

  if not found then
    return jsonb_build_object(
      'allowed', false,
      'reason', 'module_not_found',
      'effective_role', 'guest',
      'module_id', p_module_id,
      'access_mode', null,
      'matched_grant_type', null,
      'matched_grant_target', null
    );
  end if;

  if requested_module.access_mode in ('public', 'demo') then
    return jsonb_build_object(
      'allowed', true,
      'reason', requested_module.access_mode,
      'effective_role', 'public',
      'module_id', requested_module.id,
      'access_mode', requested_module.access_mode,
      'matched_grant_type', null,
      'matched_grant_target', null
    );
  end if;

  if current_user_id is null then
    return jsonb_build_object(
      'allowed', false,
      'reason', 'authentication_required',
      'effective_role', 'guest',
      'module_id', requested_module.id,
      'access_mode', requested_module.access_mode,
      'matched_grant_type', null,
      'matched_grant_target', null
    );
  end if;

  if coalesce(((select auth.jwt()) ->> 'is_anonymous')::boolean, false) then
    return jsonb_build_object(
      'allowed', false,
      'reason', 'anonymous_account_not_allowed',
      'effective_role', 'guest',
      'module_id', requested_module.id,
      'access_mode', requested_module.access_mode,
      'matched_grant_type', null,
      'matched_grant_target', null
    );
  end if;

  select profiles.tier, coalesce(profiles.unlocked_modules, '{}'::text[])
  into current_tier, current_legacy_unlocks
  from public.user_profiles as profiles
  where profiles.id = current_user_id
  limit 1;

  if not found then
    return jsonb_build_object(
      'allowed', false,
      'reason', 'profile_required',
      'effective_role', 'guest',
      'module_id', requested_module.id,
      'access_mode', requested_module.access_mode,
      'matched_grant_type', null,
      'matched_grant_target', null
    );
  end if;

  if current_tier = 'admin' then
    return jsonb_build_object(
      'allowed', true,
      'reason', 'admin',
      'effective_role', 'admin',
      'module_id', requested_module.id,
      'access_mode', requested_module.access_mode,
      'matched_grant_type', 'admin',
      'matched_grant_target', '*'
    );
  end if;

  select entitlements.grant_type, entitlements.target_id, entitlements.access_level
  into matched_grant
  from public.module_entitlements as entitlements
  where entitlements.user_id = current_user_id
    and entitlements.revoked_at is null
    and entitlements.starts_at <= now()
    and (entitlements.expires_at is null or entitlements.expires_at > now())
    and (
      (entitlements.grant_type = 'module' and entitlements.target_id = requested_module.id)
      or (entitlements.grant_type = 'bundle' and entitlements.target_id = requested_module.bundle)
      or (entitlements.grant_type = 'syllabus' and entitlements.target_id = requested_module.syllabus)
    )
  order by
    case entitlements.access_level when 'teacher' then 0 else 1 end,
    case entitlements.grant_type when 'module' then 0 when 'bundle' then 1 else 2 end
  limit 1;

  if found then
    return jsonb_build_object(
      'allowed', true,
      'reason', 'entitlement',
      'effective_role', matched_grant.access_level,
      'module_id', requested_module.id,
      'access_mode', requested_module.access_mode,
      'matched_grant_type', matched_grant.grant_type,
      'matched_grant_target', matched_grant.target_id
    );
  end if;

  -- Transitional compatibility for PINs created before module_entitlements.
  if '*' = any(current_legacy_unlocks) then
    legacy_type := 'all';
    legacy_target := '*';
  elsif requested_module.id = any(current_legacy_unlocks) then
    legacy_type := 'module';
    legacy_target := requested_module.id;
  elsif requested_module.bundle = any(current_legacy_unlocks) then
    legacy_type := 'bundle';
    legacy_target := requested_module.bundle;
  elsif requested_module.syllabus = any(current_legacy_unlocks) then
    legacy_type := 'syllabus';
    legacy_target := requested_module.syllabus;
  elsif requested_module.id = 'spm-en-social-media'
    and 'Social_Media_Masterclass' = any(current_legacy_unlocks) then
    legacy_type := 'module';
    legacy_target := 'Social_Media_Masterclass';
  end if;

  if legacy_type is not null then
    return jsonb_build_object(
      'allowed', true,
      'reason', 'legacy_entitlement',
      'effective_role', 'student',
      'module_id', requested_module.id,
      'access_mode', requested_module.access_mode,
      'matched_grant_type', legacy_type,
      'matched_grant_target', legacy_target
    );
  end if;

  return jsonb_build_object(
    'allowed', false,
    'reason', 'not_entitled',
    'effective_role', 'student',
    'module_id', requested_module.id,
    'access_mode', requested_module.access_mode,
    'matched_grant_type', null,
    'matched_grant_target', null
  );
end;
$$;

comment on function public.can_launch_module(text) is
  'Canonical shadow-compatible launch decision for public, demo, admin, entitlement, and legacy access.';

revoke all on function public.can_launch_module(text) from public;
grant execute on function public.can_launch_module(text) to anon, authenticated;
