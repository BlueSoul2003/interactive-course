-- Phase 1 of the protected module boundary.
--
-- This migration is deliberately shadow-compatible: the live portal continues
-- to use user_profiles.unlocked_modules while the new entitlement model and
-- can_launch_module() RPC are verified. No existing module route is removed.

alter table public.modules
  add column if not exists access_mode text;

update public.modules
set access_mode = 'protected'
where access_mode is null;

alter table public.modules
  alter column access_mode set default 'protected',
  alter column access_mode set not null;

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conrelid = 'public.modules'::regclass
      and conname = 'modules_access_mode_check'
  ) then
    alter table public.modules
      add constraint modules_access_mode_check
      check (access_mode in ('public', 'demo', 'protected'));
  end if;
end
$$;

